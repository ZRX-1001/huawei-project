const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require(process.argv[2] || 'typescript');
const source = fs.readFileSync(path.join(__dirname, '../entry/src/main/ets/services/SidebarService.ets'), 'utf8');
const exported = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS,
  target: ts.ScriptTarget.ES2020 } }).outputText, { exports: exported });
const sidebar = exported.SidebarService;
const features = [{ id: 'home', name: '智能助理' }, { id: 'study', name: '学习助手' }, { id: 'career', name: '求职实验室' }];
const sessions = Array.from({ length: 12 }, (_, index) => ({ id: `chat-${index}`, title: index === 1 ? '数据结构复习' : `会话${index}`,
  featureId: index < 5 ? 'study' : 'home', createdAt: 100 + index, updatedAt: 1000 - index }));
const prefs = sidebar.defaults();
prefs.expandedWorkspaceIds = ['study'];
let view = sidebar.view(sessions.slice().reverse(), features, prefs);
assert.equal(view.workspaces.find(g => g.feature.id === 'study').totalCount, 5);
assert.equal(view.workspaces.find(g => g.feature.id === 'study').sessions.length, 3);
assert.equal(view.workspaces.find(g => g.feature.id === 'study').expanded, true);
assert.equal(view.workspaces.find(g => g.feature.id === 'home').expanded, false);
assert.equal(view.recent.length, 8);
const owned = view.workspaces.find(g => g.feature.id === 'study').sessions[0];
assert.equal(owned.id, view.recent[0].id, 'workspace and recents must reference the same conversation');
assert.equal(owned.updatedAt, 1000, 'grouping must not change message dates');
assert.equal(sessions[0].updatedAt, 1000);
prefs.expandedHistoryIds = ['study'];
prefs.showAllRecent = true;
view = sidebar.view(sessions, features, prefs);
assert.equal(view.workspaces.find(g => g.feature.id === 'study').sessions.length, 5);
assert.equal(view.recent.length, 12);
const moved = sessions.map(s => s.id === 'chat-0' ? { ...s, featureId: 'career' } : s);
view = sidebar.view(moved, features, prefs);
assert.equal(view.workspaces.find(g => g.feature.id === 'study').totalCount, 4);
assert.equal(view.workspaces.find(g => g.feature.id === 'career').sessions[0].id, 'chat-0');
assert.equal(view.recent[0].featureId, 'career');
view = sidebar.view(moved.filter(s => s.id !== 'chat-0'), features, prefs);
assert.equal(view.workspaces.find(g => g.feature.id === 'career').totalCount, 0);
assert.ok(!view.recent.some(s => s.id === 'chat-0'), 'deleting one record must remove both representations');
view = sidebar.view(sessions, features, prefs, '数据结构');
assert.equal(view.workspaces.length, 1);
assert.equal(view.workspaces[0].feature.id, 'study');
assert.equal(view.workspaces[0].sessions[0].title, '数据结构复习');
assert.equal(view.recent.length, 1);
view = sidebar.view(sessions, features, prefs, '学习助手');
assert.equal(view.workspaces[0].sessions.length, 5);
assert.equal(view.recent.length, 5);
assert.equal(sidebar.view(sessions, features, prefs, '不存在的会话').recentCount, 0);
assert.equal(sidebar.normalize(undefined).panelVisible, true);
assert.equal(sidebar.normalize({ panelVisible: false, expandedWorkspaceIds: [123, 'study'] }).panelVisible, false);
assert.deepEqual(Array.from(sidebar.normalize({ expandedWorkspaceIds: [123, 'study'] }).expandedWorkspaceIds), ['study']);
assert.equal(sidebar.normalize({ leftWidth: 999, rightWidth: 1 }).leftWidth, 400);
assert.equal(sidebar.normalize({ leftWidth: 999, rightWidth: 1 }).rightWidth, 240);
assert.equal(sidebar.normalize({ leftWidth: NaN, rightWidth: Infinity }).leftWidth, 256);
assert.equal(sidebar.normalize({ leftWidth: NaN, rightWidth: Infinity }).rightWidth, 274);
const recycled = [{ ...sessions[0], featureId: 'trash', deletedAt: 100 }, { ...sessions[1], featureId: 'trash', deletedAt: 200 }, ...sessions.slice(2)];
view = sidebar.view(recycled, [...features, { id: 'trash', name: '回收站' }], prefs);
assert.equal(view.recentCount, 10);
assert.ok(view.recent.every(s => s.featureId !== 'trash'));
assert.equal(view.workspaces.find(g => g.feature.id === 'trash').sessions[0].id, 'chat-1', 'trash uses deletion time');
view = sidebar.view(recycled, [...features, { id: 'trash', name: '回收站' }], prefs, '数据结构');
assert.equal(view.recentCount, 0);
assert.equal(view.workspaces.find(g => g.feature.id === 'trash').sessions[0].id, 'chat-1');
console.log('PASS: shared workspace/recent identities, stable dates, independent folders, previews, search, workspace moves and synchronized deletion.');
