const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const ts = require(process.argv[2] || 'typescript');
const source = fs.readFileSync(path.join(__dirname, '../entry/src/main/ets/services/LocalAgentConfigService.ets'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
let cache = new Map(), disk = new Map(), failFlush = false, nextId = 1, rawReads = 0;
const store = { getSync: (key, fallback) => cache.has(key) ? cache.get(key) : fallback,
  putSync: (key, value) => cache.set(key, value), deleteSync: key => cache.delete(key),
  flushSync() { if (failFlush) throw Error('simulated storage failure'); disk = new Map(cache); } };
const out = {};
vm.runInNewContext(compiled, { exports: out, require(name) {
  if (name === '@kit.ArkData') return { preferences: { getPreferencesSync: () => store,
    removePreferencesFromCacheSync: () => { cache = new Map(disk); } } };
  if (name === '@kit.ArkTS') return { util: { generateRandomUUID: () => `profile-${nextId++}`,
    TextDecoder: { create: () => ({ decodeToString: value => new TextDecoder().decode(value) }) } } };
  throw Error('Unexpected dependency: ' + name);
} });
const service = out.LocalAgentConfigService;
const a = { baseUrl: 'https://provider-a.example.invalid/v1', model: 'model-a', apiKey: 'private-test-profile-a' };
const b = { baseUrl: 'https://provider-b.example.invalid/v1', model: 'model-b', apiKey: 'private-test-profile-b' };
const context = { resourceManager: { async getRawFileContent() { rawReads++; return new TextEncoder().encode(JSON.stringify(a)); } } };
const plain = value => JSON.parse(JSON.stringify(value));
const reset = () => { cache = new Map(); disk = new Map(); failFlush = false; rawReads = 0; };
(async () => {
  reset(); cache.set('settings', JSON.stringify(a)); disk = new Map(cache);
  let archive = await service.loadProfiles(context);
  assert.equal(archive.items.length, 1); assert.equal(archive.activeId, archive.items[0].id);
  assert.deepEqual(plain(service.active(archive)), a);
  assert.equal(cache.has('settings'), false, 'migration removes the old single-config credential copy');
  assert.equal(rawReads, 0, 'saved legacy config wins over bundled config');
  assert.equal((await service.loadProfiles(context)).items.length, 1, 'migration is idempotent');
  const originalId = archive.activeId;
  archive = service.save(context, '', '备用服务', b, false);
  const alternateId = archive.items[1].id;
  assert.equal(archive.activeId, originalId, 'save-only does not silently switch the active provider');
  assert.deepEqual(plain(await service.load(context)), a);
  archive = service.select(context, alternateId);
  const stale = new Map(cache);
  stale.set('profiles_v1', JSON.stringify({ ...archive, activeId: originalId })); cache = stale;
  assert.deepEqual(plain(await service.load(context)), b, 'background task loader reads the selected provider');
  const summary = service.summaries(archive);
  assert.deepEqual(Object.keys(summary[0]).sort(), ['id', 'model', 'name']);
  assert.ok(!JSON.stringify(summary).includes('private-test-profile'));
  service.save(context, originalId, '主配置改名', { ...a, model: 'model-a-v2' }, false);
  assert.equal((await service.load(context)).model, 'model-b', 'editing another profile preserves active credentials');
  cache = new Map(disk);
  assert.equal(service.readProfiles(context).activeId, alternateId, 'active selection survives a fresh preference read');
  assert.equal(service.readProfiles(context).items[0].model, 'model-a-v2');
  const detached = service.readProfiles(context); detached.items[0].apiKey = 'external mutation';
  assert.equal(service.readProfiles(context).items[0].apiKey, a.apiKey, 'caller mutations cannot change stored credentials');
  const before = cache.get('profiles_v1');
  failFlush = true;
  assert.throws(() => service.select(context, originalId), /保存失败/);
  failFlush = false;
  assert.equal(cache.get('profiles_v1'), before, 'failed flush restores the cache');
  cache = new Map(disk);
  assert.equal(cache.get('profiles_v1'), before, 'failed flush preserves the durable selection');
  assert.throws(() => service.save(context, '', '', { ...a, baseUrl: 'file:///private' }, true), /服务地址/);
  assert.throws(() => service.save(context, '', '', { ...a, model: '' }, true), /模型名称/);
  assert.throws(() => service.save(context, '', 'x'.repeat(61), a, true), /60/);
  assert.throws(() => service.save(context, 'deleted-id', 'x', a, true), /已被删除/);
  assert.equal(cache.get('profiles_v1'), before, 'validation failures are non-mutating');
  archive = service.remove(context, originalId);
  assert.equal(archive.activeId, alternateId, 'deleting an inactive profile preserves selection');
  archive = service.remove(context, alternateId);
  assert.equal(archive.items.length, 0); assert.deepEqual(plain(await service.load(context)), plain(service.blank()));
  assert.equal(rawReads, 0, 'deleting the final profile never revives the bundled API');
  assert.equal((await service.loadProfiles(context)).items.length, 0);
  archive = service.save(context, '', '', { ...a, model: 'long-model-'.repeat(12) }, false);
  assert.equal(archive.items[0].name.length, 60, 'an optional name remains optional for long model IDs');
  reset();
  archive = await service.loadProfiles(context);
  assert.equal(rawReads, 1); assert.deepEqual(plain(service.active(archive)), a, 'first launch imports a valid local config');
  const id = archive.activeId;
  service.save(context, '', '另一个模型', b, true);
  archive = service.remove(context, service.readProfiles(context).activeId);
  assert.equal(archive.activeId, id, 'deleting active profile selects a remaining saved configuration');
  service.saveRuntime(context, service.blank());
  assert.equal(service.readProfiles(context).items.length, 1, 'compatibility clear only clears selection');
  assert.deepEqual(plain(await service.load(context)), plain(service.blank()));
  reset(); cache.set('settings', JSON.stringify(service.blank())); disk = new Map(cache);
  assert.equal((await service.loadProfiles(context)).items.length, 0); assert.equal(rawReads, 0, 'legacy explicit clear is preserved');
  reset();
  let releaseRaw;
  const delayed = { resourceManager: { getRawFileContent: () => new Promise(resolve => { releaseRaw = resolve; }) } };
  const pending = service.loadProfiles(delayed);
  archive = service.save(delayed, '', '用户刚保存', b, true);
  releaseRaw(new TextEncoder().encode(JSON.stringify(a)));
  assert.equal((await pending).activeId, archive.activeId, 'late bootstrap cannot overwrite a user save');
  reset();
  for (let i = 0; i < 20; i++) service.save(context, '', '配置' + i, { ...a, model: 'model-' + i }, i === 0);
  assert.throws(() => service.save(context, '', '超限', a, true), /20/);
  assert.equal(service.readProfiles(context).items.length, 20);
  reset(); cache.set('profiles_v1', '{broken'); disk = new Map(cache);
  await assert.rejects(service.loadProfiles(context), /原配置已保留/);
  assert.equal(await service.load(context), undefined, 'corrupt archive cannot silently fall back to another API');
  assert.equal(cache.get('profiles_v1'), '{broken'); assert.equal(rawReads, 0);
  console.log('PASS: multi-API migration, isolated profiles/keys, save-only, selection and background reads, restart, deletion, empty-state precedence, failed-save rollback, bounds and bootstrap races.');
})().catch(error => { console.error(error); process.exitCode = 1; });
